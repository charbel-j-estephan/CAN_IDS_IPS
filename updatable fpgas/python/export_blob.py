"""Turn a trained sklearn forest into one model blob, and from that blob the
.mif for the FPGA's boot ROM and a C array for the STM32.

    py -3.13 export_blob.py --model <rf5_d9_p5_time.joblib> --out build/blobs/p5

Writes in --out: model.bin  model.hex (for $readmemh)  model.mif  model_blob.h
The exporter reads the blob back and checks it gives the same class as
sklearn's hard vote before it writes anything.
"""
import argparse
import math
import os
import sys
import zlib

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "python"))

from forest import hard_vote_predict  # noqa: E402

import blob_format as bf  # noqa: E402

ROM_BYTES = 6 * 1024        # boot ROM: 6 M9K


def convert_tree(tree):
    """sklearn tree -> list of levels of (feature, threshold, left, right), split
    nodes only. A leaf lives inside its parent as {1, class}."""
    t = tree.tree_
    if t.node_count == 1:                 # the root is a leaf: always go left to it
        cls = int(np.argmax(t.value[0][0]))
        return [[(0, bf.THRESH_MAX, bf.LEAF | cls, bf.LEAF | cls)]]

    levels = []
    this_level = [0]
    while this_level:
        next_level = []
        for n in this_level:
            for c in (t.children_left[n], t.children_right[n]):
                if t.children_left[c] != -1:
                    next_level.append(int(c))
        position = {n: i for i, n in enumerate(next_level)}

        def child(c):
            if t.children_left[c] == -1:
                return bf.LEAF | int(np.argmax(t.value[c][0]))
            return position[int(c)]

        rows = []
        for n in this_level:
            # Features are integers, so x <= 148.5 is exactly x <= 148.
            thr = math.floor(t.threshold[n])
            if not 0 <= thr <= bf.THRESH_MAX:
                raise ValueError("threshold %r does not fit" % t.threshold[n])
            rows.append((int(t.feature[n]), thr, child(t.children_left[n]), child(t.children_right[n])))
        levels.append(rows)
        this_level = next_level
    return levels


def model_hash(bundle):
    """The 32 bit hash at the end of the model name (export_c.model_id)."""
    h = 0
    for est in bundle["model"].estimators_:
        t = est.tree_
        for a in (t.feature, t.threshold, t.children_left, t.children_right,
                  np.argmax(t.value, axis=-1)):
            h = zlib.crc32(np.ascontiguousarray(a).tobytes(), h)
    return zlib.crc32(np.asarray(bundle.get("known_ids", []), dtype=np.int64).tobytes(), h)


def mask_payload(X, feat_bytes):
    """Only the data bytes the model reads, as the FPGA sees them at feat_ready."""
    X = np.array(X, dtype=np.int64)
    if feat_bytes < 8:
        X[:, 2 + feat_bytes:] = 0
    return X


def pick_selftests(model, X, n_classes):
    """One frame of each class the forest answers, then frames from the start."""
    y = hard_vote_predict(model, X)
    picked = []
    for c in range(n_classes):
        hits = np.flatnonzero(y == c)
        if len(hits):
            picked.append(int(hits[0]))
    for i in range(len(X)):
        if len(picked) >= bf.N_SELFTEST_MAX:
            break
        if i not in picked:
            picked.append(i)
    out = []
    for i in picked[:bf.N_SELFTEST_MAX]:
        features = [int(v) for v in X[i]] + [0] * (bf.N_FEAT_MAX - X.shape[1])
        out.append((features, int(y[i])))
    return out


def write_outputs(blob, out):
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "model.bin"), "wb") as f:
        f.write(blob)
    with open(os.path.join(out, "model.hex"), "w") as f:
        f.write("".join("%02x\n" % b for b in blob))
    if len(blob) > ROM_BYTES:
        print("Note: %d bytes does not fit the %d byte boot ROM; model.mif not written"
              % (len(blob), ROM_BYTES))
    else:
        with open(os.path.join(out, "model.mif"), "w") as f:
            f.write("WIDTH=8;\nDEPTH=%d;\nADDRESS_RADIX=UNS;\nDATA_RADIX=HEX;\nCONTENT BEGIN\n" % ROM_BYTES)
            for i, b in enumerate(blob):
                f.write("  %d : %02X;\n" % (i, b))
            f.write("  [%d..%d] : FF;\nEND;\n" % (len(blob), ROM_BYTES - 1))
    with open(os.path.join(out, "model_blob.h"), "w") as f:
        f.write("// Generated by updatable fpgas/python/export_blob.py. Do not edit by hand.\n"
                "#include <stdint.h>\n\nstatic const uint32_t model_blob_len = %d;\n"
                "static const uint8_t model_blob[%d] = {\n" % (len(blob), len(blob)))
        for i in range(0, len(blob), 16):
            f.write("    " + ", ".join("0x%02x" % b for b in blob[i:i + 16]) + ",\n")
        f.write("};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", required=True, help="a .joblib from python/train.py")
    ap.add_argument("--out", required=True)
    ap.add_argument("--version", type=lambda s: int(s, 0), default=1, help="monotonic version counter")
    ap.add_argument("--device-id", type=lambda s: int(s, 0), default=bf.DEVICE_ANY)
    ap.add_argument("--check-frames", type=int, default=2000000,
                    help="test frames compared with sklearn before writing")
    args = ap.parse_args()

    import joblib
    bundle = joblib.load(args.model)
    model = bundle["model"]
    n_classes = len(model.classes_)
    feat_bytes = int(bundle.get("payload_bytes", 8))
    known = bundle.get("known_ids", [])
    n_features = model.n_features_in_

    trees = [convert_tree(e) for e in model.estimators_]
    X = mask_payload(bundle["X_test"], feat_bytes)
    selftests = pick_selftests(model, X[:50000], n_classes)
    mid = model_hash(bundle)

    blob = bf.build(trees, n_features, n_classes, feat_bytes, known, selftests, mid,
                    args.version, device_id=args.device_id)
    h = bf.parse(blob)

    check = X[:args.check_frames]
    got = bf.forest_votes(h["trees"], check, n_classes)
    want = hard_vote_predict(model, check)
    bad = int((got != want).sum())
    if bad:
        raise SystemExit("Blob differs from sklearn on %d of %d frames" % (bad, len(check)))

    write_outputs(blob, args.out)
    splits = sum(len(l) for t in trees for l in t)
    print("%s: model id %08x, version %d, %d trees, %d levels, %d splits, reads %d data bytes"
          % (os.path.basename(args.model), mid, args.version, len(trees), h["depth"], splits, feat_bytes))
    print("blob %d bytes, CRC %08x, %d self test vectors, widest level %d of %d"
          % (len(blob), h["crc"], len(selftests),
             max(len(l) for t in trees for l in t), bf.NODES_PER_LEVEL_MAX))
    print("Blob agrees with sklearn hard vote on %d of %d test frames" % (len(check) - bad, len(check)))


if __name__ == "__main__":
    main()
