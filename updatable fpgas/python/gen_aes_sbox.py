"""Writes rtl/security/aes_sbox.v: AES's S-box (FIPS-197 section 5.1.1) as a
registered ROM, one look-up per clock. The table is computed here from its
definition (inverse in GF(2^8), then the affine map), not typed by hand, and
checked against the values FIPS-197 prints for 00, 01, 53 and FF.

    py -3.13 gen_aes_sbox.py

Quartus turns the initialised array into an M9K ROM; on an ASIC it is a ROM
macro or gates.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "rtl", "security", "aes_sbox.v")


def gmul(a, b):
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0x1B
        b >>= 1
    return p


def inverse(a):
    if a == 0:
        return 0
    for b in range(1, 256):
        if gmul(a, b) == 1:
            return b
    raise AssertionError


def rotl8(x, s):
    return ((x << s) | (x >> (8 - s))) & 0xFF


def sbox(a):
    b = inverse(a)
    return b ^ rotl8(b, 1) ^ rotl8(b, 2) ^ rotl8(b, 3) ^ rotl8(b, 4) ^ 0x63


def main():
    table = [sbox(a) for a in range(256)]
    # Values printed in FIPS-197 Figure 7.
    assert table[0x00] == 0x63 and table[0x01] == 0x7C and table[0x53] == 0xED and table[0xFF] == 0x16
    assert sorted(table) == list(range(256))          # a permutation
    # An initialised array rather than a 256-way case: Quartus infers the same
    # M9K ROM (altsyncram, mode ROM) from both, and Icarus simulates the array
    # about 3 times faster (40 of these tick on every clock of the whole design).
    lines = [
        "// AES S-box (FIPS-197 5.1.1) as a ROM with a registered output: the byte",
        "// for `a` is on `q` one clock later. Generated by python/gen_aes_sbox.py from",
        "// the S-box's definition; do not edit by hand. Quartus makes an M9K ROM of it.",
        "module aes_sbox (",
        "    input  wire       clk,",
        "    input  wire [7:0] a,",
        "    output reg  [7:0] q",
        ");",
        "    reg [7:0] rom [0:255];",
        "    initial begin",
    ]
    for a, v in enumerate(table):
        lines.append("        rom[8'h%02X] = 8'h%02X;" % (a, v))
    lines += [
        "    end",
        "    always @(posedge clk) q <= rom[a];",
        "endmodule",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("Wrote %s" % os.path.normpath(OUT))


if __name__ == "__main__":
    main()
